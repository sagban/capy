#!/usr/bin/env python3
"""Write .firebaserc, app/Config/Secrets.xcconfig, and functions/.env from capy.env.

The plist fills any placeholder Google and project fields. Edit capy.env, then run this again.
"""

from __future__ import annotations

import argparse
import plistlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ENV_PATH = ROOT / "capy.env"
EXAMPLE_PATH = ROOT / "capy.env.example"
PLIST_PATH = ROOT / "app" / "capy" / "GoogleService-Info.plist"
FIREBASERC_PATH = ROOT / ".firebaserc"
SECRETS_PATH = ROOT / "app" / "Config" / "Secrets.xcconfig"
FUNCTIONS_ENV_PATH = ROOT / "functions" / ".env"

KEYS = (
    "CAPY_GCP_PROJECT",
    "CAPY_REGION",
    "CAPY_MCP_SERVICE",
    "CAPY_MCP_URL",
    "FIRESTORE_DATABASE_ID",
    "GOOGLE_CLOUD_LOCATION",
    "VERTEX_GEMINI_MODEL",
    "CAPY_PHOENIX",
    "FIREBASE_WEB_API_KEY",
    "CAPY_GOOGLE_CLIENT_ID",
    "CAPY_GOOGLE_REVERSED_CLIENT_ID",
)

DEFAULTS = {
    "CAPY_GCP_PROJECT": "your-gcp-project",
    "CAPY_REGION": "us-central1",
    "CAPY_MCP_SERVICE": "capy-mcp",
    "CAPY_MCP_URL": "https://your-cloud-run-host/mcp/",
    "FIRESTORE_DATABASE_ID": "capy",
    "GOOGLE_CLOUD_LOCATION": "global",
    "VERTEX_GEMINI_MODEL": "gemini-3.5-flash",
    "CAPY_PHOENIX": "1",
    "FIREBASE_WEB_API_KEY": "",
    "CAPY_GOOGLE_CLIENT_ID": "",
    "CAPY_GOOGLE_REVERSED_CLIENT_ID": "",
}

PLACEHOLDERS = {
    "",
    "your-gcp-project",
    "YOUR_GCP_OR_FIREBASE_PROJECT_ID",
    "https://your-cloud-run-host/mcp/",
    "your-client-id.apps.googleusercontent.com",
    "com.googleusercontent.apps.your-client-id",
}


def load_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for raw in path.read_text().splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip()
    return values


def blank(value: str | None) -> bool:
    return (value or "").strip() in PLACEHOLDERS


def fill(values: dict[str, str], key: str, incoming: str | None) -> None:
    if incoming and blank(values.get(key)):
        values[key] = incoming.strip()


def from_plist() -> dict[str, str]:
    if not PLIST_PATH.exists():
        return {}
    data = plistlib.loads(PLIST_PATH.read_bytes())
    return {
        "CAPY_GCP_PROJECT": str(data.get("PROJECT_ID") or ""),
        "FIREBASE_WEB_API_KEY": str(data.get("API_KEY") or ""),
        "CAPY_GOOGLE_CLIENT_ID": str(data.get("CLIENT_ID") or ""),
        "CAPY_GOOGLE_REVERSED_CLIENT_ID": str(data.get("REVERSED_CLIENT_ID") or ""),
    }


def from_secrets_xcconfig() -> dict[str, str]:
    if not SECRETS_PATH.exists():
        return {}
    mapping = {
        "CAPY_FIREBASE_PROJECT_ID": "CAPY_GCP_PROJECT",
        "CAPY_MCP_URL": "CAPY_MCP_URL",
        "CAPY_GOOGLE_CLIENT_ID": "CAPY_GOOGLE_CLIENT_ID",
        "CAPY_GOOGLE_REVERSED_CLIENT_ID": "CAPY_GOOGLE_REVERSED_CLIENT_ID",
    }
    found: dict[str, str] = {}
    for raw in SECRETS_PATH.read_text().splitlines():
        line = raw.strip()
        if not line or line.startswith("//") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        dest = mapping.get(key.strip())
        if dest:
            found[dest] = value.strip()
    return found


def write_env(values: dict[str, str]) -> None:
    lines = [
        "# Generated values live here. Edit this file, then run ./configure.sh.",
        "# ./deploy.sh reads it and writes CAPY_MCP_URL after Cloud Run is up.",
        "",
    ]
    for key in KEYS:
        lines.append(f"{key}={values.get(key, '')}")
    ENV_PATH.write_text("\n".join(lines) + "\n")


def write_functions_env(values: dict[str, str]) -> None:
    FUNCTIONS_ENV_PATH.write_text(
        "# Generated by ./configure.sh from capy.env. Edit capy.env, then run ./configure.sh.\n"
        f"GOOGLE_CLOUD_LOCATION={values['GOOGLE_CLOUD_LOCATION']}\n"
        f"VERTEX_GEMINI_MODEL={values['VERTEX_GEMINI_MODEL']}\n"
        f"FIRESTORE_DATABASE_ID={values['FIRESTORE_DATABASE_ID']}\n"
        "GRPC_DNS_RESOLVER=native\n"
        "OBJC_DISABLE_INITIALIZE_FORK_SAFETY=YES\n"
        f"CAPY_PHOENIX={values['CAPY_PHOENIX']}\n"
        "PHOENIX_COLLECTOR_ENDPOINT=http://127.0.0.1:6006\n"
        "PHOENIX_PROJECT_NAME=capy-harness\n"
    )


def write_outputs(values: dict[str, str]) -> None:
    project = values["CAPY_GCP_PROJECT"]
    FIREBASERC_PATH.write_text(
        "{\n"
        '  "projects": {\n'
        f'    "default": "{project}"\n'
        "  }\n"
        "}\n"
    )
    SECRETS_PATH.write_text(
        "// Generated by ./configure.sh from capy.env. Edit capy.env, then run ./configure.sh.\n"
        f"CAPY_FIREBASE_PROJECT_ID = {values['CAPY_GCP_PROJECT']}\n"
        f"CAPY_MCP_URL = {values['CAPY_MCP_URL']}\n"
        f"CAPY_GOOGLE_CLIENT_ID = {values['CAPY_GOOGLE_CLIENT_ID']}\n"
        f"CAPY_GOOGLE_REVERSED_CLIENT_ID = {values['CAPY_GOOGLE_REVERSED_CLIENT_ID']}\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--set", action="append", default=[], metavar="KEY=VALUE")
    args = parser.parse_args()

    if not ENV_PATH.exists() and EXAMPLE_PATH.exists():
        ENV_PATH.write_text(EXAMPLE_PATH.read_text())

    values = dict(DEFAULTS)
    values.update(load_env(ENV_PATH))
    for key, incoming in from_secrets_xcconfig().items():
        fill(values, key, incoming)
    for key, incoming in from_plist().items():
        fill(values, key, incoming)
    for item in args.set:
        key, value = item.split("=", 1)
        values[key.strip()] = value.strip()

    missing = [key for key in KEYS if key not in values]
    if missing:
        print(f"capy.env is missing {', '.join(missing)}", file=sys.stderr)
        return 1

    write_env(values)
    write_outputs(values)
    write_functions_env(values)
    print(f"Wrote {ENV_PATH.name}, .firebaserc, app/Config/Secrets.xcconfig, and functions/.env")
    if blank(values["CAPY_GCP_PROJECT"]):
        print("Set CAPY_GCP_PROJECT in capy.env, then run ./configure.sh again.", file=sys.stderr)
        return 1
    if blank(values["CAPY_MCP_URL"]):
        print("CAPY_MCP_URL is empty until ./deploy.sh finishes.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
