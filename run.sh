#!/usr/bin/env bash
# Start Auth + Functions emulators (+ optional Phoenix) for local iOS (scheme: capy Local).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")" && pwd)"
cd "$ROOT"

FUNCTIONS_DIR="$ROOT/functions"
VENV="$FUNCTIONS_DIR/venv"
PHOENIX_PID=""

cleanup() {
  if [[ -n "${PHOENIX_PID}" ]] && kill -0 "${PHOENIX_PID}" 2>/dev/null; then
    kill "${PHOENIX_PID}" 2>/dev/null || true
  fi
}
trap cleanup EXIT INT TERM

if [[ ! -d "$VENV" ]]; then
  echo "Creating functions/venv (python3.12)…"
  python3.12 -m venv "$VENV"
fi

# shellcheck disable=SC1091
source "$VENV/bin/activate"
pip install -q -r "$FUNCTIONS_DIR/requirements.txt"
# Phoenix UI server (not imported by the Functions worker — keeps the runtime slim).
pip install -q "arize-phoenix>=8.0.0"

if [[ ! -f "$FUNCTIONS_DIR/.env" ]]; then
  cp "$FUNCTIONS_DIR/.env.example" "$FUNCTIONS_DIR/.env"
  echo "Created functions/.env from .env.example"
fi

# shellcheck disable=SC1091
set -a
# Load Phoenix flags for this shell (Firebase loads .env into the Functions runtime separately).
# shellcheck disable=SC1090
source "$FUNCTIONS_DIR/.env"
set +a

if [[ ! -f "$FUNCTIONS_DIR/.secret.local" ]]; then
  cat >"$FUNCTIONS_DIR/.secret.local" <<'EOF'
# Emulator overrides for SecretParam (gitignored). Keeps the worker off Secret Manager.
# Paste a data.gov key if you need USDA; seed catalog works without it.
USDA_FDC_API_KEY=local-placeholder
API_ACCESS_TOKEN_SECRET=local-placeholder
EOF
  echo "Created functions/.secret.local (placeholder secrets)"
fi

# gRPC c-ares often fails on corp DNS ("Could not contact DNS servers" → Firestore timeouts).
export GRPC_DNS_RESOLVER="${GRPC_DNS_RESOLVER:-native}"
export GOOGLE_CLOUD_QUOTA_PROJECT="${GOOGLE_CLOUD_QUOTA_PROJECT:-capy-dogfood}"
# macOS: Python Functions workers fork after ObjC is loaded → crash unless disabled.
export OBJC_DISABLE_INITIALIZE_FORK_SAFETY="${OBJC_DISABLE_INITIALIZE_FORK_SAFETY:-YES}"
# Prefer env proxy lookup over macOS _scproxy (segfaults in gunicorn children).
export no_proxy="${no_proxy:-*}"
export NO_PROXY="${NO_PROXY:-*}"

# Physical-device builds need the Mac LAN IP (Simulator uses 127.0.0.1 in code).
LAN_IP="$(ipconfig getifaddr en0 2>/dev/null || true)"
if [[ -z "$LAN_IP" ]]; then
  LAN_IP="$(ipconfig getifaddr en1 2>/dev/null || true)"
fi
HOST_FILE="$ROOT/Config/LocalEmulatorHost.xcconfig"
if [[ -n "$LAN_IP" ]]; then
  cat >"$HOST_FILE" <<EOF
// Generated by ./run.sh — gitignored. Physical device → Mac LAN IP.
CAPYEmulatorHost = $LAN_IP
EOF
  echo "Device emulator host → $LAN_IP (Config/LocalEmulatorHost.xcconfig)"
else
  rm -f "$HOST_FILE"
  echo "No LAN IP found — Simulator-only (127.0.0.1)"
fi

CAPY_PHOENIX_FLAG="${CAPY_PHOENIX:-1}"
if [[ "${CAPY_PHOENIX_FLAG}" =~ ^(1|true|yes|on)$ ]]; then
  export CAPY_PHOENIX=1
  export PHOENIX_COLLECTOR_ENDPOINT="${PHOENIX_COLLECTOR_ENDPOINT:-http://127.0.0.1:6006}"
  export PHOENIX_PROJECT_NAME="${PHOENIX_PROJECT_NAME:-capy-harness}"
  export PHOENIX_HOST="${PHOENIX_HOST:-127.0.0.1}"
  export PHOENIX_PORT="${PHOENIX_PORT:-6006}"
  if lsof -iTCP:"${PHOENIX_PORT}" -sTCP:LISTEN >/dev/null 2>&1; then
    echo "Phoenix already on :${PHOENIX_PORT}"
  else
    echo "Starting Phoenix UI → http://${PHOENIX_HOST}:${PHOENIX_PORT}"
    phoenix serve >/tmp/capy-phoenix.log 2>&1 &
    PHOENIX_PID=$!
    sleep 2
  fi
fi

echo "Emulators: Auth :9099 · Functions :5001 · UI http://127.0.0.1:4000"
echo "Phoenix:   http://127.0.0.1:6006  (project ${PHOENIX_PROJECT_NAME:-capy-harness})"
echo "Xcode scheme → capy Local  (rebuild app after run.sh if on a physical device)"
exec npx -y firebase-tools@latest emulators:start --only auth,functions
